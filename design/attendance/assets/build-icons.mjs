const here = dirname(fileURLToPath(import.meta.url));
const icons = {};

// lucide-react 1.47 exports `__iconData.node` where it used to export
// `__iconNode`, and renamed icons are bare re-exports of their new file.
async function iconNode(name) {
  const file = `lucide-react/dist/esm/icons/${name}.mjs`;
  const mod = await import(file);
  const node = mod.__iconNode ?? mod.__iconData?.node;
  if (node) return node;
  const source = await readFile(fileURLToPath(import.meta.resolve(file)), "utf8");
  const target = source.match(/from '\.\/([a-z0-9-]+)\.mjs'/);
  if (!target) throw new Error(`no icon data for ${name}`);
  return iconNode(target[1]);
}
for (const name of NAMES) {
  icons[name] = (await iconNode(name))
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}

const out = `// Generated by build-icons.mjs from lucide-react; do not edit by hand.
(function () {
  var ICONS = ${JSON.stringify(icons, null, 2)};
  function svg(name, cls) {
    var body = ICONS[name];
    if (!body) throw new Error("unknown icon: " + name);
    return (
      '<svg class="icon' + (cls ? " " + cls : "") + '" viewBox="0 0 24 24" fill="none" ' +
      'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
      body + "</svg>"
    );
  }
  function mount(root) {
    (root || document).querySelectorAll("[data-icon]").forEach(function (el) {
      var tpl = document.createElement("template");
      tpl.innerHTML = svg(el.getAttribute("data-icon"), el.getAttribute("class"));
      el.replaceWith(tpl.content.firstChild);
    });
  }
  window.icon = svg;
  window.mountIcons = mount;
  document.addEventListener("DOMContentLoaded", function () { mount(); });
})();
`;
await writeFile(join(here, "icons.js"), out);
console.log(`wrote ${NAMES.length} icons`);
