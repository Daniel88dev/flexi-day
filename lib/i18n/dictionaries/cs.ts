/**
 * Czech plural selection: 1 → one, 2–4 → few, otherwise (0, 5+) → many.
 * Keeps interpolated counts grammatical without pulling in Intl.PluralRules.
 */
function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n);
  if (abs === 1) return one;
  if (abs >= 2 && abs <= 4) return few;
  return many;
}

